import { getMetadataArgsStorage } from "typeorm";
import { describe, expect, it } from "vitest";

import { Project } from "../projects/project.entity.js";
import { Channel } from "./channel.entity.js";

const channelColumns = () =>
  getMetadataArgsStorage().columns.filter((column) => column.target === Channel);

const findColumn = (propertyName: string) =>
  channelColumns().find((column) => column.propertyName === propertyName);

const databaseName = (column: ReturnType<typeof channelColumns>[number]) =>
  column.options.name ?? column.propertyName;

describe("Channel entity", () => {
  it("maps to the channels table", () => {
    const table = getMetadataArgsStorage().tables.find((entry) => entry.target === Channel);

    expect(table?.name).toBe("channels");
  });

  it("has exactly four columns with the expected database names and types", () => {
    const columns = channelColumns().map((column) => ({
      name: databaseName(column),
      type: column.options.type,
    }));

    expect(columns).toHaveLength(4);
    expect(columns).toEqual(
      expect.arrayContaining([
        { name: "id", type: "uuid" },
        { name: "project_id", type: "uuid" },
        { name: "kind", type: "text" },
        { name: "is_active", type: "boolean" },
      ]),
    );
  });

  it("uses explicit snake_case names for multi-word columns", () => {
    expect(findColumn("projectId")?.options.name).toBe("project_id");
    expect(findColumn("isActive")?.options.name).toBe("is_active");
  });

  it("makes id a primary uuid column generated by uuidv7()", () => {
    const id = findColumn("id");

    expect(id?.mode).toBe("regular");
    expect(id?.options.primary).toBe(true);
    expect(typeof id?.options.default).toBe("function");
    expect((id?.options.default as () => string)()).toBe("uuidv7()");
  });

  it("defaults is_active to true", () => {
    expect(findColumn("isActive")?.options.default).toBe(true);
  });

  it("has no nullable column", () => {
    for (const column of channelColumns()) {
      expect(column.options.nullable ?? false).toBe(false);
    }
  });

  it("keeps kind a plain text column without enum restriction", () => {
    const kind = findColumn("kind");

    expect(kind?.options.type).toBe("text");
    expect(kind?.options.enum).toBeUndefined();
  });

  it("does not declare a default for project_id or kind", () => {
    expect(findColumn("projectId")?.options.default).toBeUndefined();
    expect(findColumn("kind")?.options.default).toBeUndefined();
  });

  describe("project relation", () => {
    const projectRelation = () =>
      getMetadataArgsStorage().relations.find(
        (relation) => relation.target === Channel && relation.propertyName === "project",
      );

    it("is many-to-one on Project", () => {
      const relation = projectRelation();

      expect(relation?.relationType).toBe("many-to-one");
      expect((relation?.type as () => unknown)()).toBe(Project);
    });

    it("is not nullable and cascades on delete", () => {
      const relation = projectRelation();

      expect(relation?.options.nullable).toBe(false);
      expect(relation?.options.onDelete).toBe("CASCADE");
    });

    it("joins through the project_id column", () => {
      const joinColumn = getMetadataArgsStorage().joinColumns.find(
        (entry) => entry.target === Channel && entry.propertyName === "project",
      );

      expect(joinColumn?.name).toBe("project_id");
    });

    it("has no inverse side", () => {
      expect(projectRelation()?.inverseSideProperty).toBeUndefined();
    });

    it("is the only relation of Channel", () => {
      const relations = getMetadataArgsStorage().relations.filter(
        (relation) => relation.target === Channel,
      );

      expect(relations).toHaveLength(1);
    });
  });
});
