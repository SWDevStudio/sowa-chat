import { getMetadataArgsStorage } from "typeorm";
import { describe, expect, it } from "vitest";

import { Channel } from "../channels/channel.entity.js";
import { Project } from "../projects/project.entity.js";
import { Visitor } from "../visitors/visitor.entity.js";
import { Conversation } from "./conversation.entity.js";

const expectedColumns = [
  { property: "id", name: "id", type: "uuid", nullable: false },
  { property: "projectId", name: "project_id", type: "uuid", nullable: false },
  { property: "visitorId", name: "visitor_id", type: "uuid", nullable: false },
  { property: "channelId", name: "channel_id", type: "uuid", nullable: false },
  { property: "status", name: "status", type: "text", nullable: false },
  { property: "assigneeId", name: "assignee_id", type: "uuid", nullable: true },
  { property: "activeBotId", name: "active_bot_id", type: "uuid", nullable: true },
  { property: "context", name: "context", type: "jsonb", nullable: false },
  { property: "handoff", name: "handoff", type: "jsonb", nullable: true },
  { property: "lastSeq", name: "last_seq", type: "integer", nullable: false },
  { property: "lastMessageAt", name: "last_message_at", type: "timestamptz", nullable: false },
  { property: "routingCycle", name: "routing_cycle", type: "jsonb", nullable: true },
  { property: "createdAt", name: "created_at", type: "timestamptz", nullable: false },
  { property: "closedAt", name: "closed_at", type: "timestamptz", nullable: true },
  { property: "closeReason", name: "close_reason", type: "text", nullable: true },
];

const columns = () => getMetadataArgsStorage().filterColumns(Conversation);
const relations = () => getMetadataArgsStorage().filterRelations(Conversation);
const indices = () => getMetadataArgsStorage().filterIndices(Conversation);

const findColumn = (property: string) =>
  columns().find((column) => column.propertyName === property);
const findRelation = (property: string) =>
  relations().find((relation) => relation.propertyName === property);
const findJoinColumn = (property: string) =>
  getMetadataArgsStorage().filterJoinColumns(Conversation, property)[0];
const relationTarget = (property: string) =>
  (findRelation(property)?.type as (() => unknown) | undefined)?.();

describe("Conversation entity", () => {
  it("maps to the conversations table", () => {
    const table = getMetadataArgsStorage().tables.find((entry) => entry.target === Conversation);

    expect(table?.name).toBe("conversations");
  });

  it("has exactly 15 columns", () => {
    expect(columns()).toHaveLength(15);
  });

  it("does not declare unexpected columns", () => {
    const properties = columns()
      .map((column) => column.propertyName)
      .sort();

    expect(properties).toEqual(expectedColumns.map((column) => column.property).sort());
  });

  it.each(expectedColumns)(
    "column $property is stored as $name with type $type",
    ({ property, name, type }) => {
      const column = findColumn(property);

      expect(column).toBeDefined();
      expect(column?.options.name ?? column?.propertyName).toBe(name);
      expect(column?.options.type).toBe(type);
    },
  );

  it.each(expectedColumns)("column $property has nullable=$nullable", ({ property, nullable }) => {
    expect(findColumn(property)?.options.nullable === true).toBe(nullable);
  });

  it("makes nullable exactly the six optional columns", () => {
    const nullableNames = columns()
      .filter((column) => column.options.nullable === true)
      .map((column) => column.options.name ?? column.propertyName)
      .sort();

    expect(nullableNames).toEqual([
      "active_bot_id",
      "assignee_id",
      "close_reason",
      "closed_at",
      "handoff",
      "routing_cycle",
    ]);
  });

  it("uses explicit snake_case names for multi-word columns", () => {
    const multiWord = expectedColumns.filter((column) => column.name.includes("_"));

    expect(multiWord).toHaveLength(11);
    for (const { property, name } of multiWord) {
      expect(findColumn(property)?.options.name).toBe(name);
    }
  });

  it("makes id the primary uuid column generated by uuidv7()", () => {
    const id = findColumn("id");

    expect(id?.options.primary).toBe(true);
    expect(typeof id?.options.default).toBe("function");
    expect((id?.options.default as () => string)()).toBe("uuidv7()");
  });

  it("marks created_at as a create date column", () => {
    expect(findColumn("createdAt")?.mode).toBe("createDate");
  });

  it("defaults context to an empty json object", () => {
    const defaultValue = findColumn("context")?.options.default;

    expect(typeof defaultValue).toBe("function");
    expect((defaultValue as () => string)()).toBe("'{}'");
  });

  it("defaults last_seq to 0", () => {
    expect(findColumn("lastSeq")?.options.default).toBe(0);
  });

  it("defaults last_message_at to now()", () => {
    const defaultValue = findColumn("lastMessageAt")?.options.default;

    expect(typeof defaultValue).toBe("function");
    expect((defaultValue as () => string)()).toBe("now()");
  });

  it.each(["projectId", "visitorId", "channelId", "status"])(
    "column %s has no default",
    (property) => {
      expect(findColumn(property)?.options.default).toBeUndefined();
    },
  );

  it.each(["assigneeId", "activeBotId", "handoff", "routingCycle", "closedAt", "closeReason"])(
    "nullable column %s has no default",
    (property) => {
      expect(findColumn(property)?.options.default).toBeUndefined();
    },
  );

  it("keeps status and close_reason plain text columns without enum restriction", () => {
    expect(findColumn("status")?.options.enum).toBeUndefined();
    expect(findColumn("closeReason")?.options.enum).toBeUndefined();
  });

  describe("relations", () => {
    it("declares exactly three relations", () => {
      expect(relations()).toHaveLength(3);
    });

    it("project is many-to-one to Project with CASCADE and project_id join column", () => {
      const relation = findRelation("project");

      expect(relation?.relationType).toBe("many-to-one");
      expect(relationTarget("project")).toBe(Project);
      expect(relation?.options.onDelete).toBe("CASCADE");
      expect(relation?.options.nullable).toBe(false);
      expect(findJoinColumn("project")?.name).toBe("project_id");
    });

    it("visitor is many-to-one to Visitor with CASCADE and visitor_id join column", () => {
      const relation = findRelation("visitor");

      expect(relation?.relationType).toBe("many-to-one");
      expect(relationTarget("visitor")).toBe(Visitor);
      expect(relation?.options.onDelete).toBe("CASCADE");
      expect(relation?.options.nullable).toBe(false);
      expect(findJoinColumn("visitor")?.name).toBe("visitor_id");
    });

    it("channel is many-to-one to Channel without onDelete and with channel_id join column", () => {
      const relation = findRelation("channel");

      expect(relation?.relationType).toBe("many-to-one");
      expect(relationTarget("channel")).toBe(Channel);
      expect(relation?.options.onDelete).toBeUndefined();
      expect(relation?.options.nullable).toBe(false);
      expect(findJoinColumn("channel")?.name).toBe("channel_id");
    });

    it("has no relation for assignee_id and active_bot_id", () => {
      expect(findRelation("assignee")).toBeUndefined();
      expect(findRelation("activeBot")).toBeUndefined();
      expect(findRelation("assigneeId")).toBeUndefined();
      expect(findRelation("activeBotId")).toBeUndefined();
    });

    it.each([Project, Visitor, Channel])("declares no inverse side on %o", (target) => {
      const inverse = getMetadataArgsStorage()
        .filterRelations(target)
        .filter((relation) => relation.relationType === "one-to-many");

      expect(inverse).toHaveLength(0);
    });
  });

  describe("indices", () => {
    it("declares exactly two indices", () => {
      expect(indices()).toHaveLength(2);
    });

    it.each(["IDX_conversations_context", "IDX_conversations_project_status_last_message_at"])(
      "declares index %s with synchronize disabled",
      (name) => {
        const index = indices().find((entry) => entry.name === name);

        expect(index).toBeDefined();
        expect(index?.synchronize).toBe(false);
      },
    );

    it("has no index with synchronization enabled", () => {
      expect(indices().every((index) => index.synchronize === false)).toBe(true);
    });
  });
});
