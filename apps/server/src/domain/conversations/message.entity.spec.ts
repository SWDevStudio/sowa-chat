import { getMetadataArgsStorage } from "typeorm";
import { describe, expect, it } from "vitest";

import { Conversation } from "./conversation.entity.js";
import { Message } from "./message.entity.js";

const expectedColumns = [
  { property: "id", name: "id", type: "uuid", nullable: false },
  { property: "conversationId", name: "conversation_id", type: "uuid", nullable: false },
  { property: "seq", name: "seq", type: "integer", nullable: false },
  { property: "senderKind", name: "sender_kind", type: "text", nullable: false },
  { property: "senderId", name: "sender_id", type: "uuid", nullable: true },
  { property: "type", name: "type", type: "text", nullable: false },
  { property: "customType", name: "custom_type", type: "text", nullable: true },
  { property: "body", name: "body", type: "text", nullable: true },
  { property: "payload", name: "payload", type: "jsonb", nullable: true },
  { property: "isInternal", name: "is_internal", type: "boolean", nullable: false },
  { property: "clientMsgId", name: "client_msg_id", type: "uuid", nullable: true },
  { property: "createdAt", name: "created_at", type: "timestamptz", nullable: false },
];

const columns = () => getMetadataArgsStorage().filterColumns(Message);
const relations = () => getMetadataArgsStorage().filterRelations(Message);
const indices = () => getMetadataArgsStorage().filterIndices(Message);

const findColumn = (property: string) =>
  columns().find((column) => column.propertyName === property);
const findRelation = (property: string) =>
  relations().find((relation) => relation.propertyName === property);
const findJoinColumn = (property: string) =>
  getMetadataArgsStorage().filterJoinColumns(Message, property)[0];
const relationTarget = (property: string) =>
  (findRelation(property)?.type as (() => unknown) | undefined)?.();
const indexColumns = (columnList: unknown) =>
  typeof columnList === "function" ? undefined : columnList;

describe("Message entity", () => {
  it("maps to the messages table", () => {
    const table = getMetadataArgsStorage().tables.find((entry) => entry.target === Message);

    expect(table?.name).toBe("messages");
  });

  it("has exactly 12 columns", () => {
    expect(columns()).toHaveLength(12);
  });

  it("does not declare unexpected columns", () => {
    const properties = columns()
      .map((column) => column.propertyName)
      .sort();

    expect(properties).toEqual(expectedColumns.map((column) => column.property).sort());
  });

  it.each(expectedColumns)(
    "column $property is stored as $name with type $type",
    ({ property, name, type }) => {
      const column = findColumn(property);

      expect(column).toBeDefined();
      expect(column?.options.name ?? column?.propertyName).toBe(name);
      expect(column?.options.type).toBe(type);
    },
  );

  it.each(expectedColumns)("column $property has nullable=$nullable", ({ property, nullable }) => {
    expect(findColumn(property)?.options.nullable === true).toBe(nullable);
  });

  it("makes nullable exactly the five optional columns", () => {
    const nullableNames = columns()
      .filter((column) => column.options.nullable === true)
      .map((column) => column.options.name ?? column.propertyName)
      .sort();

    expect(nullableNames).toEqual(["body", "client_msg_id", "custom_type", "payload", "sender_id"]);
  });

  it("uses explicit snake_case names for multi-word columns", () => {
    const multiWord = expectedColumns.filter((column) => column.name.includes("_"));

    expect(multiWord).toHaveLength(7);
    for (const { property, name } of multiWord) {
      expect(findColumn(property)?.options.name).toBe(name);
    }
  });

  it("makes id the primary uuid column generated by uuidv7()", () => {
    const id = findColumn("id");
    const defaultValue = id?.options.default;

    expect(id?.options.primary).toBe(true);
    expect(defaultValue).toBeTypeOf("function");
    expect(typeof defaultValue === "function" ? defaultValue() : undefined).toBe("uuidv7()");
  });

  it("marks created_at as a create date column", () => {
    expect(findColumn("createdAt")?.mode).toBe("createDate");
  });

  it("defaults is_internal to false", () => {
    expect(findColumn("isInternal")?.options.default).toBe(false);
  });

  it.each([
    "conversationId",
    "seq",
    "senderKind",
    "senderId",
    "type",
    "customType",
    "body",
    "payload",
    "clientMsgId",
  ])("column %s has no default", (property) => {
    expect(findColumn(property)?.options.default).toBeUndefined();
  });

  it("keeps sender_kind and type plain text columns without enum restriction", () => {
    expect(findColumn("senderKind")?.options.enum).toBeUndefined();
    expect(findColumn("type")?.options.enum).toBeUndefined();
  });

  describe("relations", () => {
    it("declares exactly one relation", () => {
      expect(relations()).toHaveLength(1);
    });

    it("conversation is many-to-one to Conversation with CASCADE and conversation_id join column", () => {
      const relation = findRelation("conversation");

      expect(relation?.relationType).toBe("many-to-one");
      expect(relationTarget("conversation")).toBe(Conversation);
      expect(relation?.options.onDelete).toBe("CASCADE");
      expect(relation?.options.nullable).toBe(false);
      expect(findJoinColumn("conversation")?.name).toBe("conversation_id");
    });

    it("has no relation for sender_id", () => {
      expect(findRelation("sender")).toBeUndefined();
      expect(findRelation("senderId")).toBeUndefined();
    });

    it("declares no inverse side on Conversation", () => {
      const inverse = getMetadataArgsStorage()
        .filterRelations(Conversation)
        .filter((relation) => relation.relationType === "one-to-many");

      expect(inverse).toHaveLength(0);
    });
  });

  describe("indices", () => {
    it("declares exactly two indices", () => {
      expect(indices()).toHaveLength(2);
    });

    it("has a unique index on conversationId and seq", () => {
      const index = indices().find(
        (entry) =>
          JSON.stringify(indexColumns(entry.columns)) === JSON.stringify(["conversationId", "seq"]),
      );

      expect(index).toBeDefined();
      expect(index?.unique).toBe(true);
    });

    it("has a unique index on conversationId and clientMsgId", () => {
      const index = indices().find(
        (entry) =>
          JSON.stringify(indexColumns(entry.columns)) ===
          JSON.stringify(["conversationId", "clientMsgId"]),
      );

      expect(index).toBeDefined();
      expect(index?.unique).toBe(true);
    });

    it("has no non-unique index", () => {
      expect(indices().every((index) => index.unique === true)).toBe(true);
    });

    it("does not disable synchronization of its indices", () => {
      expect(indices().every((index) => index.synchronize !== false)).toBe(true);
    });
  });
});
